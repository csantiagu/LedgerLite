export function Sidebar() {
  const pathname = usePathname();
  const router = useRouter();
  const { role, clearAuth } = useAuthStore();

  const visibleItems = navItems.filter(item => {
    if (item.ownerOnly && role !== 'owner') return false;
    if (item.accountantOnly && role !== 'accountant') return false;
    return true;
  });
  const showSettings = !settingsItem.ownerOnly || role === 'owner';

  async function handleLogout() {
    await logout();
    router.replace('/login');
  }

  const NavLink = ({ item }: { item: NavItem }) => {
    const active = pathname.startsWith(item.href);
    return (
      <Link
        href={item.href}
        aria-current={active ? 'page' : undefined}
        className={`
          flex items-center gap-3 rounded-lg px-3 py-2 text-sm font-medium transition-colors
          ${active
            ? 'bg-slate-700 text-white'
            : 'text-slate-400 hover:bg-slate-700/60 hover:text-slate-100'
          }
        `}
      >
        {item.icon}
        {item.label}
      </Link>
    );
  };

  return (
    <aside className="flex h-full w-60 flex-col bg-slate-800 text-slate-100">
      {/* Logo */}
      <div className="flex h-16 items-center gap-2 border-b border-slate-700 px-5">
        <div className="flex h-8 w-8 items-center justify-center rounded-lg bg-blue-600">
          <svg className="h-5 w-5 text-white" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2} aria-hidden="true">
            <path strokeLinecap="round" strokeLinejoin="round" d="M12 6v12m-3-2.818.879.659c1.171.879 3.07.879 4.242 0 1.172-.879 1.172-2.303 0-3.182C13.536 12.219 12.768 12 12 12c-.725 0-1.45-.22-2.003-.659-1.106-.879-1.106-2.303 0-3.182s2.9-.879 4.006 0l.415.33M21 12a9 9 0 1 1-18 0 9 9 0 0 1 18 0Z" />
          </svg>
        </div>
        <span className="text-base font-semibold tracking-tight">LedgerLite</span>
      </div>

      {/* Nav */}
      <nav className="flex-1 overflow-y-auto px-3 py-4 space-y-1" aria-label="Main navigation">
        {visibleItems.map(item => <NavLink key={item.href} item={item} />)}
      </nav>

      {/* Bottom */}
      <div className="border-t border-slate-700 px-3 py-3 space-y-1">
        {role === 'owner' && <NavLink item={companySettingsItem} />}
        {showSettings && <NavLink item={settingsItem} />}
        <button
          onClick={handleLogout}
          className="flex w-full items-center gap-3 rounded-lg px-3 py-2 text-sm font-medium text-slate-400 hover:bg-slate-700/60 hover:text-slate-100 transition-colors cursor-pointer"
        >
          <svg className="h-5 w-5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5} aria-hidden="true">
            <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 9V5.25A2.25 2.25 0 0 0 13.5 3h-6a2.25 2.25 0 0 0-2.25 2.25v13.5A2.25 2.25 0 0 0 7.5 21h6a2.25 2.25 0 0 0 2.25-2.25V15M12 9l-3 3m0 0 3 3m-3-3h12.75" />
          </svg>
          Sign out
        </button>
      </div>
    </aside>
  );
}
